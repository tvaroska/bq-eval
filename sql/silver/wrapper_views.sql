-- Silver Fixed-Window Thin Wrapper Views (`ADR-035`, `ADR-048`).
-- Convenience 24-hour wrappers over every published `silver_open` and `silver_restricted` TVF.
-- Open wrapper views read ONLY `silver_open` TVFs and never touch restricted sources.

CREATE OR REPLACE VIEW `${PROJECT_ID}.${SILVER_OPEN_DATASET}.v_model_calls_24h` AS
SELECT *
FROM `${PROJECT_ID}.${SILVER_OPEN_DATASET}.model_calls`(
  TIMESTAMP_SUB(CURRENT_TIMESTAMP(), INTERVAL 24 HOUR),
  CURRENT_TIMESTAMP()
);

